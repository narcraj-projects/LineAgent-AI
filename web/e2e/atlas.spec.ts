import { test, expect } from '@playwright/test';

test('live graph atlas: audited nodes, exact sources, filters, layouts, mobile and investigation handoff', async ({page, request}) => {
  test.skip(process.env.LINEMEDIC_LIVE_BROWSER !== '1', 'Explicit opt-in to configured providers. No feedback is written.');
  const connection = await request.post('/api/connection',{data:{graph_backend:'auto'}});
  expect(connection.ok()).toBe(true);
  await page.goto('/');
  await page.getByRole('button',{name:'Graph Atlas',exact:true}).click();
  await expect(page.getByLabel('Interactive evidence graph')).toBeVisible({timeout:90000});
  const response = await request.get('/api/graph/explore?alarm_code=SYN-ALM-004');
  expect(response.status()).toBe(200);
  const graph = await response.json();
  expect(graph.history_audited_against_sql).toBe(true);
  await expect(page.getByRole('status',{name:'Graph provider',exact:true})).toHaveText(`${graph.status.provider} / ${graph.status.mode}`);
  await expect(page.getByRole('button',{name:'Alarm SYN-ALARM-004',exact:true})).toBeVisible();
  await page.screenshot({path:'../tmp/atlas-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Fix SYN-FIX-004',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Simulator correction: cap feed orientation',exact:true})).toBeVisible();
  const fix = graph.nodes.find((n: {id:string})=>n.id==='SYN-FIX-004');
  const attempts = fix.outcomes.worked+fix.outcomes.did_not_work;
  await expect(page.getByText(`${Math.round(fix.outcomes.worked/attempts*100)}% recorded worked`,{exact:false})).toBeVisible();
  await page.screenshot({path:'../tmp/atlas-fix-inspector.png',fullPage:true});
  await page.getByRole('button',{name:'Manual section SYN-SEC-007',exact:true}).click();
  const citation = page.getByRole('link',{name:/Open verified page/});
  await expect(citation).toHaveAttribute('href',/\/pages\/7\.png$/);
  await page.getByRole('button',{name:'Path view',exact:true}).click();
  await page.getByRole('button',{name:'Zoom in graph',exact:true}).click();
  await expect(page.getByLabel('Graph zoom')).toHaveText('115%');
  await page.getByRole('button',{name:'Reset graph view',exact:true}).click();
  await page.getByLabel('Search graph nodes').fill('SYN-SEC-007');
  await expect(page.getByText('1 matching nodes')).toBeVisible();
  await page.getByLabel('Search graph nodes').fill('');
  await page.getByLabel('Work orders',{exact:true}).uncheck();
  await expect(page.locator('[data-node^="SYN-WO-"]')).toHaveCount(0);
  await page.getByLabel('Work orders',{exact:true}).check();
  await page.getByLabel('Graph alarm').selectOption('SYN-ALM-020');
  await expect(page.getByRole('button',{name:'Alarm SYN-ALARM-020',exact:true})).toBeVisible({timeout:60000});
  await expect(page.getByRole('button',{name:'Alarm SYN-ALARM-004',exact:true})).toHaveCount(0);
  await page.getByLabel('Graph alarm').selectOption('SYN-ALM-004');
  await expect(page.getByRole('button',{name:'Alarm SYN-ALARM-004',exact:true})).toBeVisible({timeout:60000});
  await page.getByRole('button',{name:'Constellation',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await expect.poll(() => page.locator('.sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await expect(page.getByLabel('Interactive evidence graph')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../tmp/atlas-mobile.png',fullPage:true});
  await page.getByRole('button',{name:/Investigate this alarm/}).click();
  await expect(page.getByLabel('Alarm code')).toHaveValue('SYN-ALM-004');
  await expect(page.getByLabel('Retrieval strategy')).toHaveValue('combined');
});
